import { chromium } from "@playwright/test";
const browser = await chromium.launch();
const page = await browser.newPage();
await page.setViewportSize({ width: 1200, height: 700 });
await page.goto("http://localhost:5173/#/play/grid-walker", { waitUntil: "networkidle" });
await page.waitForSelector(".game-studio-viewport-mount canvas", { timeout: 15000 });
await page.waitForTimeout(1500);
// walk the box up-right for a moment so the second shot shows the moved box
const mount = page.locator(".game-studio-viewport-mount");
await mount.click();
await page.locator(".game-studio-viewport-mount canvas").screenshot({ path: "native/rt-probe/web_grid_center.png" });
await page.keyboard.down("ArrowRight");
await page.keyboard.down("ArrowUp");
await page.waitForTimeout(1600);
await page.keyboard.up("ArrowRight");
await page.keyboard.up("ArrowUp");
await page.waitForTimeout(300);
await page.locator(".game-studio-viewport-mount canvas").screenshot({ path: "native/rt-probe/web_grid_moved.png" });
await browser.close();
console.log("done");
